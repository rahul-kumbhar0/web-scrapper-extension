#!/usr/bin/env node
// PullRows MCP relay — a zero-dependency MCP server (Streamable HTTP transport, JSON responses)
// that forwards Claude's tool calls to the PullRows extension running in the user's Chrome.
//
//   Claude ──POST /mcp/<id>────────▶ relay ◀──GET  /bridge/<token>/next──── extension (long-poll)
//                                          ◀──POST /bridge/<token>/result──
//                                          ◀──GET  /bridge/<token>/status── (handshake)
//                                          ◀──DELETE /bridge/<token>─────── (connector turned off)
//
// Two secrets, one derived from the other:
//   token  — generated by the extension (base64url, 24–128 chars) and never shown to the user.
//            It is the *bridge* credential: whoever holds it can receive commands and post results.
//   id     — idForToken(token) = base64url(SHA-256(utf8(token))) without padding, first 32 chars.
//            The MCP link the user pastes into Claude is https://<relay>/mcp/<id>. Knowing the link
//            lets someone call tools on that browser (treat it like a password), but it does NOT let
//            them poll the bridge or forge results, because the token can't be derived from the id.
// All per-browser state is keyed by id. Only bridge routes create state; /mcp on an unknown id
// behaves as "extension not connected".
//
// Online detection: a browser is online while it has a long-poll open, or for 5 s after it was last
// seen. DELETE /bridge/<token> marks it offline at once and fails its queued and running calls.
// A 1 s sweep fails queued (undelivered) calls once the browser has been offline for 8 s, and
// delivered calls once it has been offline for 90 s. Every call also has an overall timeout
// (CALL_TIMEOUT_MS, default 240 s).
//
// Cancellation: when a call that was already delivered to the extension times out or fails
// because the browser went offline, the relay queues
//     { id: <new uuid>, tool: '__cancel', args: { id: <original command id> } }
// so the extension can abort the work. No result is expected for it (one is ignored if posted),
// and the extension should ignore a __cancel whose args.id it doesn't know.
//
// Delivery: a command handed to a long-poll whose socket is already gone, or whose response
// never finishes writing, is put back at the front of the queue. Results for a command are
// matched by its id, so a command delivered twice is resolved by whichever result arrives first.
//
//   PORT=8787 node server/mcp-relay.mjs          (binds 127.0.0.1 unless HOST is set)
//
// Env: PORT, HOST, CALL_TIMEOUT_MS, TRUST_PROXY=1 (behind a reverse proxy: use X-Forwarded-For /
// X-Forwarded-Host / X-Forwarded-Proto), PUBLIC_URL and OAUTH_SECRET (see oauth.mjs).

import http from 'node:http';
import crypto from 'node:crypto';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { TOOLS, INSTRUCTIONS } from './tools.mjs';
import { handleOAuth } from './oauth.mjs';

const PORT = Number(process.env.PORT || 8787);
const HOST = process.env.HOST || '127.0.0.1';
const TRUST_PROXY = process.env.TRUST_PROXY === '1';
const CALL_TIMEOUT_MS = Number(process.env.CALL_TIMEOUT_MS || 240000);
const POLL_WAIT_MS = 25000;
const ONLINE_WINDOW_MS = 5000; // seen this recently (or polling right now) = online
const CONNECT_GRACE_MS = 8000; // queued calls fail after the browser has been offline this long
const LOST_AFTER_MS = 90000; // running calls fail after the browser has been offline this long
const SWEEP_MS = 1000;
const MAX_BATCH = 10;
const MAX_PENDING = 6; // undelivered + in-flight commands per browser
const MAX_BROWSERS = 20000;
const MAX_POLLS_PER_BROWSER = 4;
const MAX_QUEUED_CANCELS = 20;
const MAX_CONCURRENT_UPLOADS = 32;
const MCP_BODY_LIMIT = 1024 * 1024;
const RESULT_BODY_LIMIT = 25 * 1024 * 1024;
const TOOL_CALLS_PER_MIN = 120; // per browser
const OAUTH_REQ_PER_MIN = 30; // per IP: /register, /authorize, /token
const BRIDGE_REQ_PER_MIN = 240; // per IP: /bridge status, DELETE, and anything that creates state
const SUPPORTED_VERSIONS = ['2025-11-25', '2025-06-18', '2025-03-26', '2024-11-05'];
export const VERSION = '1.0.0';
const TOKEN_RE = /^[A-Za-z0-9_-]{24,128}$/;
const ID_RE = /^[A-Za-z0-9_-]{32}$/;

/** The MCP link id for a bridge token: base64url(SHA-256(utf8(token))), unpadded, first 32 chars. */
export function idForToken(token) {
  return crypto.createHash('sha256').update(String(token), 'utf8').digest('base64url').replace(/=+$/, '').slice(0, 32);
}

const NOT_CONNECTED = 'The PullRows extension is not connected. Ask the user to open Chrome, open the PullRows side panel → Settings → Claude connector, and make sure it says "Connected".';
const toolError = (text) => ({ isError: true, content: [{ type: 'text', text }] });

// ---------- rate limiting (token buckets) ----------
function bucket(perMin) {
  return { tokens: perMin, at: Date.now(), perMin };
}
function take(bk) {
  const now = Date.now();
  bk.tokens = Math.min(bk.perMin, bk.tokens + ((now - bk.at) / 60000) * bk.perMin);
  bk.at = now;
  if (bk.tokens < 1) return false;
  bk.tokens -= 1;
  return true;
}
const ipBuckets = new Map(); // `${kind}|${ip}` -> bucket
function ipAllowed(req, kind, perMin) {
  const key = `${kind}|${clientIp(req)}`;
  let bk = ipBuckets.get(key);
  if (!bk) {
    if (ipBuckets.size >= 200000) ipBuckets.clear(); // crude memory bound under a flood
    bk = bucket(perMin);
    ipBuckets.set(key, bk);
  }
  return take(bk);
}
function clientIp(req) {
  if (TRUST_PROXY) {
    const fwd = String(req.headers['x-forwarded-for'] || '').split(',')[0].trim();
    if (fwd) return fwd;
  }
  return req.socket.remoteAddress || 'unknown';
}

// ---------- per-browser state ----------
// id -> { queue: [cmd], polls: Set<poll>, pending: Map(cmdId -> call), lastSeen, rate, uploads, info }
const browsers = new Map();

function idle(b) {
  return !online(b) && !b.pending.size && !b.polls.size && b.queue.every((c) => c.tool === '__cancel');
}

// Only bridge routes (which prove knowledge of the token) create state.
function browserForToken(token) {
  const id = idForToken(token);
  let b = browsers.get(id);
  if (!b) {
    if (browsers.size >= MAX_BROWSERS) {
      for (const [k, v] of browsers) if (idle(v)) browsers.delete(k);
      if (browsers.size >= MAX_BROWSERS) return null;
    }
    b = { id, queue: [], polls: new Set(), pending: new Map(), lastSeen: 0, rate: bucket(TOOL_CALLS_PER_MIN), uploads: 0, info: {} };
    browsers.set(id, b);
  }
  return b;
}

const online = (b) => b.polls.size > 0 || Date.now() - b.lastSeen < ONLINE_WINDOW_MS;
const offlineFor = (b) => (b.polls.size > 0 ? 0 : Date.now() - b.lastSeen);

// Hand queued commands to open long-polls.
function pump(b) {
  while (b.queue.length && b.polls.size) {
    const poll = b.polls.values().next().value;
    b.polls.delete(poll);
    const cmd = b.queue.shift();
    if (!deliver(b, poll, cmd)) b.queue.unshift(cmd);
  }
}

// Write a command to a poll response. Returns false (command not consumed) if the socket is gone.
function deliver(b, poll, cmd) {
  const { req, res } = poll;
  poll.done = true;
  clearTimeout(poll.timer);
  b.lastSeen = Date.now();
  if (res.destroyed || res.writableEnded || req.socket?.destroyed) return false;
  const call = b.pending.get(cmd.id);
  if (call) { call.delivered = true; call.deliveredAt = Date.now(); }
  res.on('close', () => {
    if (res.writableFinished) return;
    // The write never completed: put the command back unless it was answered meanwhile.
    if (call ? b.pending.get(cmd.id) === call : cmd.tool === '__cancel') {
      if (call) call.delivered = false;
      if (!b.queue.includes(cmd)) b.queue.unshift(cmd);
      pump(b);
    }
  });
  send(res, 200, cmd);
  return true;
}

function enqueueCancel(b, origId) {
  b.queue.unshift({ id: crypto.randomUUID(), tool: '__cancel', args: { id: origId } });
  const cancels = b.queue.filter((c) => c.tool === '__cancel');
  if (cancels.length > MAX_QUEUED_CANCELS) {
    const drop = new Set(cancels.slice(MAX_QUEUED_CANCELS));
    b.queue = b.queue.filter((c) => !drop.has(c));
  }
  pump(b);
}

// Settle a pending call with an error result; queue a __cancel if the extension already had it.
function failCall(b, id, text) {
  const call = b.pending.get(id);
  if (!call) return;
  clearTimeout(call.timer);
  b.pending.delete(id);
  b.queue = b.queue.filter((c) => c.id !== id);
  if (call.delivered) enqueueCancel(b, id);
  call.resolve(toolError(text));
}

function dispatch(b, tool, args) {
  const id = crypto.randomUUID();
  return new Promise((resolve) => {
    const timer = setTimeout(() => {
      const call = b.pending.get(id);
      if (!call) return;
      failCall(b, id, call.delivered || online(b)
        ? `The PullRows extension did not finish "${tool}" within ${Math.round(CALL_TIMEOUT_MS / 1000)}s. Try a smaller job (fewer pages/URLs).`
        : NOT_CONNECTED);
    }, CALL_TIMEOUT_MS);
    b.pending.set(id, { resolve, timer, tool, delivered: false, at: Date.now() });
    b.queue.push({ id, tool, args });
    pump(b);
  });
}

// Fail calls stuck on an offline browser; forget idle browsers.
let lastCleanup = Date.now();
setInterval(() => {
  const now = Date.now();
  for (const b of browsers.values()) {
    if (!b.pending.size || b.polls.size) continue;
    for (const [id, call] of [...b.pending]) {
      if (!call.delivered && offlineFor(b) > CONNECT_GRACE_MS) failCall(b, id, NOT_CONNECTED);
      else if (call.delivered && offlineFor(b) > LOST_AFTER_MS) failCall(b, id, `The connection to the PullRows extension was lost while running ${call.tool}.`);
    }
  }
  if (now - lastCleanup > 60000) {
    lastCleanup = now;
    for (const [id, b] of browsers) if (idle(b) && now - b.lastSeen > 60000) browsers.delete(id);
    for (const [k, bk] of ipBuckets) if (bk.tokens + ((now - bk.at) / 60000) * bk.perMin >= bk.perMin) ipBuckets.delete(k);
  }
}, SWEEP_MS).unref();

// ---------- HTTP helpers ----------
const CORS_BASE = {
  'access-control-allow-methods': 'GET, POST, DELETE, OPTIONS',
  'access-control-allow-headers': 'content-type, mcp-session-id, mcp-protocol-version, authorization, last-event-id',
  'access-control-expose-headers': 'mcp-session-id, www-authenticate',
  'access-control-max-age': '600',
};
// Browser origins allowed to talk to /mcp (DNS-rebinding guard from the MCP transport spec).
function originAllowed(origin) {
  try {
    const u = new URL(origin);
    if (u.origin !== origin) return false; // must be a bare origin
    if (u.protocol === 'https:' && (u.hostname === 'claude.ai' || u.hostname === 'claude.com') && !u.port) return true;
    if (u.protocol === 'https:' && /^([a-z0-9-]+\.)+anthropic\.com$/.test(u.hostname) && !u.port) return true;
    if ((u.protocol === 'http:' || u.protocol === 'https:') && (u.hostname === 'localhost' || u.hostname === '127.0.0.1')) return true;
    return false;
  } catch { return false; }
}

function send(res, status, body, headers = {}) {
  if (res.headersSent || res.destroyed) return;
  const isJson = body !== undefined && typeof body !== 'string';
  res.writeHead(status, {
    ...(res.corsHeaders || {}),
    ...(isJson ? { 'content-type': 'application/json' } : body !== undefined ? { 'content-type': 'text/html; charset=utf-8' } : {}),
    'cache-control': 'no-store',
    'x-content-type-options': 'nosniff',
    ...headers,
  });
  res.end(isJson ? JSON.stringify(body) : body);
}

class HttpError extends Error {
  constructor(status, message) { super(message); this.status = status; }
}

async function readJson(req, limit) {
  if (Number(req.headers['content-length'] || 0) > limit) throw new HttpError(413, 'Request too large');
  const chunks = [];
  let size = 0;
  for await (const c of req) {
    size += c.length;
    if (size > limit) throw new HttpError(413, 'Request too large');
    chunks.push(c);
  }
  const raw = Buffer.concat(chunks).toString('utf8');
  try { return raw ? JSON.parse(raw) : null; } catch { throw new HttpError(400, 'Parse error'); }
}

// ---------- MCP (JSON-RPC over Streamable HTTP, JSON responses) ----------
const rpcError = (id, code, message) => ({ jsonrpc: '2.0', id: id ?? null, error: { code, message } });

async function handleRpc(id, msg) {
  const reqId = msg?.id;
  const reply = (result) => ({ jsonrpc: '2.0', id: reqId, result });
  const fail = (code, message) => rpcError(reqId, code, message);
  if (!msg || typeof msg !== 'object' || msg.jsonrpc !== '2.0' || typeof msg.method !== 'string') return fail(-32600, 'Invalid Request');
  if (reqId === undefined || reqId === null) return null; // notification: nothing to send back
  const { method, params } = msg;

  switch (method) {
    case 'initialize': {
      const requested = params?.protocolVersion;
      return reply({
        protocolVersion: SUPPORTED_VERSIONS.includes(requested) ? requested : SUPPORTED_VERSIONS[0],
        capabilities: { tools: { listChanged: false } },
        serverInfo: { name: 'pullrows', title: 'PullRows (Chrome)', version: VERSION },
        instructions: INSTRUCTIONS,
      });
    }
    case 'ping':
      return reply({});
    case 'tools/list':
      return reply({ tools: TOOLS });
    case 'tools/call': {
      const name = params?.name;
      if (!TOOLS.some((t) => t.name === name)) return fail(-32602, `Unknown tool: ${name}`);
      const args = params?.arguments ?? {};
      if (typeof args !== 'object' || Array.isArray(args)) return fail(-32602, 'arguments must be an object');
      const b = browsers.get(id);
      if (!b) return reply(toolError(NOT_CONNECTED)); // never create state from /mcp
      if (!take(b.rate)) return { ...fail(-32000, 'Rate limit exceeded: too many PullRows tool calls this minute. Wait a moment and retry.'), rateLimited: true };
      if (offlineFor(b) > CONNECT_GRACE_MS) return reply(toolError(NOT_CONNECTED));
      if (b.pending.size >= MAX_PENDING) return reply(toolError(`PullRows is busy with ${b.pending.size} tasks — wait for them to finish.`));
      return reply(await dispatch(b, name, args));
    }
    case 'resources/list':
      return reply({ resources: [] });
    case 'prompts/list':
      return reply({ prompts: [] });
    default:
      return fail(-32601, `Method not found: ${method}`);
  }
}

async function handleMcp(req, res, id) {
  if (req.method === 'GET') return send(res, 405, { error: 'This server does not offer an SSE stream; use POST.' }, { allow: 'POST, DELETE' });
  if (req.method === 'DELETE') return send(res, 200, {});
  if (req.method !== 'POST') return send(res, 405, { error: 'Method not allowed' }, { allow: 'POST, DELETE' });
  let body;
  try { body = await readJson(req, MCP_BODY_LIMIT); } catch (e) {
    if (e.status === 413) return send(res, 413, rpcError(null, -32600, 'Request too large'));
    return send(res, 400, rpcError(null, -32700, 'Parse error'));
  }
  const sessionHeader = { 'mcp-session-id': String(req.headers['mcp-session-id'] || crypto.randomUUID()).slice(0, 128) };
  const strip = (m) => { if (m?.rateLimited) { const { rateLimited, ...rest } = m; return rest; } return m; };
  if (Array.isArray(body)) {
    if (!body.length) return send(res, 400, rpcError(null, -32600, 'Invalid Request: empty batch'));
    if (body.length > MAX_BATCH) return send(res, 400, rpcError(null, -32600, `Invalid Request: batches are limited to ${MAX_BATCH} messages`));
    const out = [];
    for (const m of body) { // sequentially: one batch must not fan out into parallel browser work
      const r = await handleRpc(id, m);
      if (r) out.push(strip(r));
    }
    return out.length ? send(res, 200, out, sessionHeader) : send(res, 202, undefined, sessionHeader);
  }
  const out = await handleRpc(id, body);
  if (!out) return send(res, 202, undefined, sessionHeader);
  if (out.rateLimited) return send(res, 429, strip(out), { ...sessionHeader, 'retry-after': '30' });
  return send(res, 200, out, sessionHeader);
}

// ---------- bridge for the extension ----------
function handleNext(req, res, b, url) {
  b.lastSeen = Date.now();
  b.info = { version: String(url.searchParams.get('v') || b.info.version || '').slice(0, 32) };
  const poll = { req, res, done: false, timer: null };
  const cmd = b.queue.shift();
  if (cmd) {
    if (deliver(b, poll, cmd)) return;
    b.queue.unshift(cmd);
    return;
  }
  // Too many parallel polls for one browser: release the oldest.
  if (b.polls.size >= MAX_POLLS_PER_BROWSER) {
    const oldest = b.polls.values().next().value;
    b.polls.delete(oldest);
    endPoll(b, oldest);
  }
  poll.timer = setTimeout(() => { b.polls.delete(poll); endPoll(b, poll); }, POLL_WAIT_MS);
  res.on('close', () => {
    if (poll.done) return;
    poll.done = true;
    clearTimeout(poll.timer);
    b.polls.delete(poll);
    b.lastSeen = Date.now();
  });
  b.polls.add(poll);
}

function endPoll(b, poll, status = 204) {
  if (poll.done) return;
  poll.done = true;
  clearTimeout(poll.timer);
  b.lastSeen = Date.now();
  send(poll.res, status);
}

let uploads = 0; // result bodies currently being received (all browsers)
async function handleResult(req, res, b) {
  b.lastSeen = Date.now();
  if (![...b.pending.values()].some((c) => c.delivered)) { req.resume(); return send(res, 404, { error: 'unknown or expired command' }); }
  if (b.uploads >= MAX_PENDING || uploads >= MAX_CONCURRENT_UPLOADS) { req.resume(); return send(res, 503, { error: 'busy' }, { 'retry-after': '1' }); }
  b.uploads++;
  uploads++;
  let body;
  try { body = await readJson(req, RESULT_BODY_LIMIT); } catch (e) { return send(res, e.status || 400, { error: e.status === 413 ? 'result too large' : 'bad json' }); } finally { b.uploads--; uploads--; }
  b.lastSeen = Date.now();
  const call = typeof body?.id === 'string' ? b.pending.get(body.id) : null;
  if (!call) return send(res, 404, { error: 'unknown or expired command' });
  clearTimeout(call.timer);
  b.pending.delete(body.id);
  b.queue = b.queue.filter((c) => c.id !== body.id);
  const content = Array.isArray(body.content) ? body.content : [{ type: 'text', text: String(body.error || 'No result') }];
  call.resolve({ content, isError: !!body.isError });
  return send(res, 200, { ok: true });
}

// The connector was turned off: offline now, fail everything.
function handleDisconnect(res, b) {
  for (const poll of [...b.polls]) { b.polls.delete(poll); endPoll(b, poll); }
  b.lastSeen = 0;
  for (const [id, call] of [...b.pending]) {
    failCall(b, id, call.delivered ? `The PullRows connector was turned off while running ${call.tool}.` : NOT_CONNECTED);
  }
  return send(res, 200, { ok: true, online: false });
}

