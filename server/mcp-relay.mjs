const OAUTH_ROUTES = new Set(['/register', '/authorize', '/token']);

function route(parts) {
  if (parts[0] === 'mcp') return '/mcp/:id';
  if (parts[0] === 'bridge') return `/bridge/:token${parts[2] ? `/${parts[2]}` : ''}`;
  if (parts[0] === '.well-known') return `/.well-known/${parts[1] || ''}`;
  return `/${parts[0] || ''}`;
}

async function onRequest(req, res) {
  let parts = [];
  try {
    const url = new URL(req.url, 'http://localhost');
    parts = url.pathname.split('/').filter(Boolean);
    const isMcp = parts[0] === 'mcp';
    const isWellKnown = parts[0] === '.well-known';

    // CORS only where browsers legitimately need it.
    const origin = req.headers.origin;
    if (isMcp) {
      if (origin !== undefined && !originAllowed(origin)) return send(res, 403, { error: 'Origin not allowed' });
      if (origin) res.corsHeaders = { ...CORS_BASE, 'access-control-allow-origin': origin, vary: 'Origin' };
    } else if (isWellKnown) {
      res.corsHeaders = { ...CORS_BASE, 'access-control-allow-origin': '*' };
    }
    if (req.method === 'OPTIONS') return send(res, 204);

    if (OAUTH_ROUTES.has(url.pathname) && !ipAllowed(req, 'oauth', OAUTH_REQ_PER_MIN)) {
      return send(res, 429, { error: 'too_many_requests' }, { 'retry-after': '60' });
    }
    if (await handleOAuth(req, res, url, send)) return;
    if (!parts.length) return send(res, 200, STATUS_PAGE);
    if (parts[0] === 'health' && parts.length === 1) return send(res, 200, { ok: true, version: VERSION });

    if (isMcp && parts.length === 2) {
      if (!ID_RE.test(parts[1])) return send(res, 404, { error: 'Unknown or invalid connector link' });
      return await handleMcp(req, res, parts[1]);
    }

    if (parts[0] === 'bridge' && (parts.length === 2 || parts.length === 3)) {
      const token = parts[1];
      if (!TOKEN_RE.test(token)) return send(res, 404, { error: 'Unknown or invalid token' });
      const sub = parts[2] || '';
      const known = browsers.get(idForToken(token));
      const limited = sub === 'status' || sub === '' || !known;
      if (limited && !ipAllowed(req, 'bridge', BRIDGE_REQ_PER_MIN)) return send(res, 429, { error: 'too many requests' }, { 'retry-after': '30' });

      if (sub === '' && req.method === 'DELETE') return known ? handleDisconnect(res, known) : send(res, 200, { ok: true, online: false });
      if (sub === 'result' && req.method === 'POST') {
        if (!known) { req.resume(); return send(res, 404, { error: 'unknown or expired command' }); }
        return await handleResult(req, res, known);
      }
      if ((sub === 'next' || sub === 'status') && req.method === 'GET') {
        const b = known || browserForToken(token);
        if (!b) return send(res, 503, { error: 'Relay is at capacity, try again later' }, { 'retry-after': '30' });
        if (sub === 'next') return handleNext(req, res, b, url);
        b.lastSeen = Date.now();
        return send(res, 200, { online: true, version: VERSION });
      }
      return send(res, 405, { error: 'Method not allowed' });
    }
    return send(res, 404, { error: 'Not found' });
  } catch (e) {
    console.error(`relay error: ${req.method} ${route(parts)}: ${e?.stack || e}`);
    if (!res.headersSent) send(res, 500, { error: 'Internal error' });
    else res.destroy();
  }
}

// requestTimeout bounds receiving a request (headers + body), not the wait for our response, so
// long-polls and long tool calls are unaffected while slow-upload sockets get cut off.
const server = http.createServer({ requestTimeout: 120000, headersTimeout: 66000, keepAliveTimeout: 65000 }, onRequest);
